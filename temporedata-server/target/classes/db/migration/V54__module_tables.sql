-- =============================================================================
-- V54: ops/sync/engine-ingestion/asset/svc/dev module tables
--
-- Purpose:
--   Introduces idempotent CREATE TABLE IF NOT EXISTS for the tables backing the
--   remaining front-end modules that were not covered by earlier migrations:
--     * ops/sync        -> zy_sync          (data sync jobs)
--     * ops/engine      -> zy_engine        (Spark/Flink compute engines)
--     * ops/ingestion   -> zy_ingestion     (data ingestion jobs)
--     * svc/apilog      -> zy_apilog        (API call logs)
--     * asset/mydata    -> zy_mydata        (granted-data registry)
--     * asset/datacenter-> zy_datacenter    (data-center config + counters)
--     * asset/permapproval-> zy_permapproval(permission approval flows)
--     * svc/form        -> zy_form          (dynamic forms)
--     * dev/func        -> zy_func          (UDF function registry)
--     * dev/globalvar   -> zy_globalvar     (global variables)
--     * dev/dependency  -> zy_dependency    (dependency libraries)
--
-- Notes:
--   1. All are idempotent CREATE TABLE IF NOT EXISTS (no DDL impact on existing rows).
--   2. Every table uses a 32-char VARCHAR PK for the UUID generated by the entity.
--   3. ops_repo / ops_build already exist from V9 and are intentionally NOT re-declared.
-- =============================================================================

CREATE TABLE IF NOT EXISTS zy_sync (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), source_datasource_id VARCHAR(32), source_table VARCHAR(255), target_datasource_id VARCHAR(32),
    target_table VARCHAR(255), sync_mode VARCHAR(32), incremental_column VARCHAR(255), incremental_value VARCHAR(255),
    batch_size VARCHAR(64), config TEXT, status VARCHAR(32), row_count INTEGER, last_run_time VARCHAR(64),
    duration VARCHAR(64), error_msg TEXT, create_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='Data sync jobs';

CREATE TABLE IF NOT EXISTS zy_engine (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), type VARCHAR(32), jar_path VARCHAR(255), main_class VARCHAR(255), sql_content TEXT,
    python_file VARCHAR(255), flink_home VARCHAR(255), parallelism VARCHAR(64), job_manager_memory VARCHAR(64),
    task_manager_memory VARCHAR(64), task_slots INTEGER, savepoint_path VARCHAR(255), args TEXT, conf TEXT,
    status VARCHAR(32), job_id VARCHAR(255), last_run_time VARCHAR(64), duration VARCHAR(64), error_msg TEXT,
    create_time VARCHAR(32), master VARCHAR(255), deploy_mode VARCHAR(32), driver_memory VARCHAR(64),
    executor_memory VARCHAR(64), executor_cores INTEGER, num_executors INTEGER, app_id VARCHAR(255),
    PRIMARY KEY (id)
) COMMENT='Spark/Flink compute engines';

CREATE TABLE IF NOT EXISTS zy_ingestion (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), type VARCHAR(32), datasource_id VARCHAR(32), target_table VARCHAR(255), config TEXT,
    datasource_name VARCHAR(255), status VARCHAR(32), row_count INTEGER, last_run_time VARCHAR(64),
    error_msg TEXT, create_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='Data ingestion jobs';

CREATE TABLE IF NOT EXISTS zy_apilog (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    api_name VARCHAR(255), api_path VARCHAR(255), method VARCHAR(16), request_ip VARCHAR(64), request_params TEXT,
    response_code INTEGER, response_body TEXT, cost_time BIGINT, caller_id VARCHAR(64), create_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='API call logs';

CREATE TABLE IF NOT EXISTS zy_mydata (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    user_id VARCHAR(32), resource_type VARCHAR(32), resource_id VARCHAR(32), resource_name VARCHAR(255),
    expire_time VARCHAR(64), access_type VARCHAR(32), granted_by VARCHAR(32), create_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='Granted-data registry';

CREATE TABLE IF NOT EXISTS zy_datacenter (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    datasource_count BIGINT, table_count BIGINT, workflow_count BIGINT, api_count BIGINT, sync_task_count BIGINT,
    quality_rule_count BIGINT, name VARCHAR(255), description TEXT, category VARCHAR(64), config TEXT,
    datasource_id VARCHAR(32), refresh_interval INTEGER, status VARCHAR(32), create_time VARCHAR(32), update_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='Data-center config + counters';

CREATE TABLE IF NOT EXISTS zy_permapproval (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    resource_type VARCHAR(32), resource_id VARCHAR(32), resource_name VARCHAR(255), access_type VARCHAR(32),
    reason TEXT, expire_time VARCHAR(64), applicant_id VARCHAR(32), applicant_name VARCHAR(255), status VARCHAR(32),
    approver_id VARCHAR(32), approver_name VARCHAR(255), approve_comment TEXT, create_time VARCHAR(32), update_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='Permission approval flows';

CREATE TABLE IF NOT EXISTS zy_form (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), description TEXT, config TEXT, status VARCHAR(32), share_token VARCHAR(64),
    create_time VARCHAR(32), update_time VARCHAR(32), form_id VARCHAR(64), data TEXT, submitter_ip VARCHAR(64),
    submit_time VARCHAR(64),
    PRIMARY KEY (id)
) COMMENT='Dynamic forms';

CREATE TABLE IF NOT EXISTS zy_func (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), type VARCHAR(32), language VARCHAR(32), script TEXT, description TEXT, status VARCHAR(32),
    create_time VARCHAR(32),
    PRIMARY KEY (id)
) COMMENT='UDF function registry';

CREATE TABLE IF NOT EXISTS zy_globalvar (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), status VARCHAR(32), description TEXT,
    PRIMARY KEY (id)
) COMMENT='Global variables';

CREATE TABLE IF NOT EXISTS zy_dependency (
    id VARCHAR(32) NOT NULL,
    create_date_time DATETIME, create_by VARCHAR(32), update_date_time DATETIME, update_by VARCHAR(32), tenant_id VARCHAR(32),
    name VARCHAR(255), status VARCHAR(32), description TEXT,
    PRIMARY KEY (id)
) COMMENT='Dependency libraries';